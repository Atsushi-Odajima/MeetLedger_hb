#!/usr/bin/env node
// MeetLedger operating cost model. Prints Markdown tables for OPERATING_COSTS.md.
// All unit prices: USD, checked 2026-10-02 (see docs/SOURCE_NOTES.md). Several were only confirmed via search snippets
// of the vendors' official pages -> re-check on the official pricing pages before quoting to customers.
// Usage: node scripts/cost-model.mjs [--rtf 0.08] [--usd-jpy 150]

const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, arr) => (v.startsWith('--') ? [...a, [v.slice(2), arr[i + 1]]] : a), []));
const USD_JPY = Number(args['usd-jpy'] ?? 150); // FX assumption, not a sourced price
const LOCAL_RTF = Number(args.rtf ?? 0.1); // local ASR real-time factor (CPU seconds per audio second); measured value goes here

const P = {
  transcription: {
    'Local (sherpa-onnx SenseVoice)': { perHour: 0, source: 'no API fee (compute only)' },
    'AssemblyAI Universal-3.5 Pro + 話者分離': { perHour: 0.23, source: '$0.21/h + $0.02/h [検索要約]' },
    'ElevenLabs Scribe v2 (話者分離込み)': { perHour: 0.22, source: '$0.22/h [検索要約]' },
    'Deepgram Nova-3 Multilingual + 話者分離': { perHour: 0.432, source: '$0.0052/min + $0.0020/min [検索要約]' },
    'OpenAI gpt-4o-mini-transcribe (話者分離なし, 2027-02-26終了予定)': { perHour: 0.18, source: '$0.003/min [検索要約]' },
  },
  llm: {
    'Local rules (外部送信なし)': { in: 0, out: 0, source: 'no API fee' },
    'Claude Haiku 4.5': { in: 1, out: 5, source: '$1/$5 per MTok [一次]' },
    'Claude Sonnet 5.5': { in: 2, out: 10, source: '$2/$10 per MTok [一次]' },
    'OpenAI GPT-6 Luna': { in: 0.1, out: 0.5, source: '$0.10/$0.50 per MTok [検索要約]' },
  },
  embedding: { 'local-hash': 0, 'OpenAI text-embedding-3-small': 0.02 },
  s3GbMonth: 0.025, // AWS S3 Standard ap-northeast-1 [一次 price list]
  sesPer1000: 0.1, // Amazon SES ap-northeast-1 [一次 price list]
  rds: { 't4g.micro': 18.3, 't4g.small': 36.5, 't4g.medium': 73.7 }, // RDS PostgreSQL Single-AZ Tokyo, monthly [一次 price list]
  rdsStorageGbMonth: 0.138,
};

// Usage assumptions (editable). Japanese speech ~330 chars/min.
const U = {
  transcriptCharsPerHour: 20000,
  tokensPerChar: 1.0, // conservative for Japanese; newer Claude tokenizers may use ~30% more tokens
  extractionOverheadTokens: 3000,
  extractionOutputTokens: 3000,
  asksPerMeetingHour: 2,
  askInputTokens: 6000,
  askOutputTokens: 600,
  polishPerMeetingHour: 1,
  polishInputTokens: 800,
  polishOutputTokens: 300,
  embeddingTokenFactor: 1.2,
  audioMBPerHour: { 'Opus 32kbps (ブラウザ/Desktop録音)': 14.4, 'M4A 64kbps (アップロード)': 28.8, '動画 720p (アップロード)': 900 },
  emailsPerMeetingHour: 3,
  dbMBPerHour: 0.5, // transcript + indexes + ledger, generous
};

const HOURS = [10, 50, 200, 1000];
const RETENTION_MONTHS = { 'Never / Until processed': 0, '7 days': 7 / 30, '30 days': 1, '90 days (custom)': 3 };

const fmt = (usd) => `$${usd.toFixed(2)} (約¥${Math.round(usd * USD_JPY).toLocaleString('ja-JP')})`;
const transcriptTokens = U.transcriptCharsPerHour * U.tokensPerChar;

function llmPerHour(l) {
  const inTok = transcriptTokens + U.extractionOverheadTokens + U.asksPerMeetingHour * U.askInputTokens + U.polishPerMeetingHour * U.polishInputTokens;
  const outTok = U.extractionOutputTokens + U.asksPerMeetingHour * U.askOutputTokens + U.polishPerMeetingHour * U.polishOutputTokens;
  return (inTok * l.in + outTok * l.out) / 1e6;
}

function dbTier(h) {
  return h <= 50 ? 't4g.micro' : h <= 200 ? 't4g.small' : 't4g.medium';
}

const PLANS = [
  { name: 'A. Local-first（既定）', t: 'Local (sherpa-onnx SenseVoice)', l: 'Local rules (外部送信なし)', e: 'local-hash' },
  { name: 'B. Cloud economy', t: 'AssemblyAI Universal-3.5 Pro + 話者分離', l: 'Claude Haiku 4.5', e: 'OpenAI text-embedding-3-small' },
  { name: 'C. Cloud standard', t: 'Deepgram Nova-3 Multilingual + 話者分離', l: 'Claude Sonnet 5.5', e: 'OpenAI text-embedding-3-small' },
  { name: 'D. Local音声 + Cloud AI', t: 'Local (sherpa-onnx SenseVoice)', l: 'Claude Haiku 4.5', e: 'local-hash' },
];

const out = [];
out.push(`<!-- generated by scripts/cost-model.mjs (USD/JPY=${USD_JPY}, local RTF=${LOCAL_RTF}) -->`);
out.push('### 1時間あたりの変動費（API/送信系のみ）\n');
out.push('| 項目 | 単価 | 1音声時間あたり |\n|---|---|---|');
for (const [k, v] of Object.entries(P.transcription)) out.push(`| 文字起こし: ${k} | ${v.source} | ${fmt(v.perHour)} |`);
for (const [k, v] of Object.entries(P.llm)) out.push(`| AI(要約/抽出/Ask/文面): ${k} | ${v.source} | ${fmt(llmPerHour(v))} |`);
for (const [k, v] of Object.entries(P.embedding)) out.push(`| Embedding: ${k} | $${v}/MTok | ${fmt((transcriptTokens * U.embeddingTokenFactor * v) / 1e6)} |`);
out.push(`| Email通知 (SES) | $0.10/1000通 | ${fmt((U.emailsPerMeetingHour * P.sesPer1000) / 1000)} |`);
out.push('');
out.push(`前提: 日本語 ${U.transcriptCharsPerHour.toLocaleString()}文字/時, ${U.tokensPerChar} token/文字, 抽出 overhead ${U.extractionOverheadTokens} + 出力 ${U.extractionOutputTokens} tokens, Ask ${U.asksPerMeetingHour}回/時 (入力${U.askInputTokens}/出力${U.askOutputTokens}), 文面調整 ${U.polishPerMeetingHour}回/時.`);
out.push('');
out.push('### 月間音声時間別の月額（プラン別、DBはRDS Single-AZ東京、音声保存はOpus 30日保持）\n');
out.push(`| プラン | ${HOURS.map((h) => `${h}時間/月`).join(' | ')} |`);
out.push(`|---|${HOURS.map(() => '---').join('|')}|`);
for (const plan of PLANS) {
  const cells = HOURS.map((h) => {
    const t = P.transcription[plan.t].perHour * h;
    const l = llmPerHour(P.llm[plan.l]) * h;
    const e = ((transcriptTokens * U.embeddingTokenFactor * P.embedding[plan.e]) / 1e6) * h;
    const s3 = ((h * U.audioMBPerHour['Opus 32kbps (ブラウザ/Desktop録音)']) / 1024) * 1 * P.s3GbMonth;
    const db = P.rds[dbTier(h)] + ((h * U.dbMBPerHour * 12) / 1024) * P.rdsStorageGbMonth;
    const mail = ((h * U.emailsPerMeetingHour) / 1000) * P.sesPer1000;
    return fmt(t + l + e + s3 + db + mail);
  });
  out.push(`| ${plan.name} | ${cells.join(' | ')} |`);
}
out.push('');
out.push(`※ DB tier: ≤50h t4g.micro / ≤200h t4g.small / それ以上 t4g.medium。DBストレージは1年分の蓄積を仮定。アプリサーバ(VM/コンテナ)費用は利用先により大きく異なるため**含めていない**（下表のCPU時間を参照）。`);
out.push('');
out.push('### 音声保存（Retention）別のストレージ費（S3 Standard 東京, 定常状態の月額）\n');
const fmts = Object.entries(U.audioMBPerHour);
out.push(`| 形式 / 保持 | ${Object.keys(RETENTION_MONTHS).join(' | ')} |`);
out.push(`|---|${Object.keys(RETENTION_MONTHS).map(() => '---').join('|')}|`);
for (const h of HOURS) {
  for (const [fname, mb] of fmts) {
    const cells = Object.values(RETENTION_MONTHS).map((months) => fmt(((h * mb) / 1024) * months * P.s3GbMonth));
    out.push(`| ${h}h/月・${fname} | ${cells.join(' | ')} |`);
  }
}
out.push('');
out.push('### Local文字起こしの計算資源（API費0の代わりにCPU時間が必要）\n');
out.push('| 月間音声 | CPU時間（RTF ' + LOCAL_RTF + '） | 処理中の一時WAV (16kHz mono) |\n|---|---|---|');
for (const h of HOURS) out.push(`| ${h}時間 | 約${(h * LOCAL_RTF).toFixed(1)} CPU時間 | 1時間の会議あたり約115MB（処理後すぐ削除） |`);
console.log(out.join('\n'));
